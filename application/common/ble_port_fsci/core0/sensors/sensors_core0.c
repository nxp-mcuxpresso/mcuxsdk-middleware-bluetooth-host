/*! *********************************************************************************
*\brief  Initialize sensors handlers
*
*\param  none
*
*\retval    none
********************************************************************************** */
void SENSORS_InitCore0Handlers(void)
{
    BLE_PortFsciRegisterOpHandler((uint8_t)g_SensorsTriggerTemperatureMeasurement_c,
                                  SENSORS_RemoteHandler);
    BLE_PortFsciRegisterOpHandler((uint8_t)g_SensorsRefreshTemperatureValue_c,
                                  SENSORS_RemoteHandler);
}

/************************************************************************************
*************************************************************************************
* Private functions
*************************************************************************************
************************************************************************************/
/*! *********************************************************************************
*\brief        Handle SENSORS_RemoteHandler call from the remote core
*
*\param  [in]  opc      Opcode of the FSCI command to be treated
*\param  [in]  len      Command payload length
*\param  [in]  pData    Pointer to command payload
*
*\retval       kStatus_SHELL_Success
********************************************************************************** */
static void SENSORS_RemoteHandler(uint8_t opc, uint8_t len, void *pData)
{
    switch (opc)
    {
        case (uint8_t)g_SensorsTriggerTemperatureMeasurement_c:
        {
            SENSORS_TriggerTemperatureMeasurement();
        }
        break;

        case (uint8_t)g_SensorsRefreshTemperatureValue_c:
        {
            (void)SENSORS_RefreshTemperatureValue();
        }
        break;

        default:
        {
            ;
        }
        break;
    }
}
